<script setup lang="ts">
/**
 * 业务域的透传出口：只写一个 `<RouterView />`。
 *
 * ## 为什么域节点需要一个组件
 *
 * 路由表里 `/calendar`、`/agent` 这类"域"自身不是页面，但没有 `component` 的
 * 父路由在 vue-router 里会让子路由**无处渲染**：`<RouterView/>` 取不到组件，
 * 内容区就是空白。给它们一个只做透传的组件，嵌套链才连得起来。
 *
 * ## 为什么五个域共用这一个文件
 *
 * `view/CalendarView.vue`、`view/AgentView.vue` … 五个文件的内容一字不差
 * （都是一个 `<RouterView/>`）。分成五个文件看着"一域一文件"，实际是五份
 * 重复的样板，改一处要记得改五处。各域文件因此只有两行实质内容：导入本组件，
 * 在模板里渲染它。
 *
 * 需要给某个域加"域级"内容时（例如历法域顶部放一条统一的历法切换器），
 * 把那个域的 `<DomainOutlet />` 换成自己的模板即可，其余四个域不受影响。
 *
 * ## 写注释时的一个坑
 *
 * 本文件的说明里**不能出现成对的 SFC 标签原文**（开始与结束标签都写全）。
 * Vue 的 SFC 词法分析只认"第一个结束标签"：注释里写一份完整示例，就等于提前
 * 关掉了本文件的脚本块，而报错是 "Invalid end tag" 与 "can contain only one
 * `<template>` element"，位置指在文件结尾，很难往注释上想。
 * 要举例就只写开始标签，或者像下面这样用文字描述。
 */
</script>

