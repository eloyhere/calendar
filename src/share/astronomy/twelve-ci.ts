/**
 * 十二次：由木星的**实际黄经**推它当前在哪一次。
 *
 * 这是「岁在星纪」那句话的可计算版本。木星历原有的十二个月是**等时段**
 * （每段 361 天），实测月首黄经差 25.61°–34.84°，**不是十二次**
 * （见 `scripts/probe-jupiter-sidereal.mjs`）。所以次必须另算。
 *
 * ## 一、次的分界点：用库里的中气
 *
 * 十二次是黄道上均分的十二个 30° 扇区。它的分界**落在十二中气上**——
 * 而中气是库里有的东西（`climate_month` / `phenology` 给出每一个中气的精确时刻，
 * 也就是太阳黄经到达 270° / 300° / 330° / 0° / … 的时刻）。
 *
 * 于是分界不需要我从文献里抄度数，只需要知道「中气的太阳黄经」这一条
 * 定义（冬至 270°、大寒 300°、雨水 330°、春分 0°、…），
 * 而这是节气的定义本身，不是额外的假设。
 *
 * ```
 * 玄枵 [270,300)  星纪 [300,330)  析木 [330,360)
 * 大火 [  0, 30)  寿星 [ 30, 60)  鹑尾 [ 60, 90)
 * 鹑火 [ 90,120)  鹑首 [120,150)  实沈 [150,180)
 * 大梁 [180,210)  降娄 [210,240)  娵訾 [240,270)
 * ```
 *
 * ## 二、次序：以《左传》那句为准
 *
 * 次的**名字**与十二辰的对应是固定的（子玄枵、丑星纪、寅析木、卯大火、
 * 辰寿星、巳鹑尾、午鹑火、未鹑首、申实沈、酉大梁、戌降娄、亥娵訾）。
 *
 * 但十二辰该按哪个方向铺在黄经上，文献里有两种说法（岁星右行、太岁左行），
 * 我不能靠记忆定。所以用一条**硬证据**来定：
 *
 * > 《左传·襄公二十八年》「岁在星纪而**淫于玄枵**」
 *
 * 「淫于」是**超过**的意思——木星从星纪走进了玄枵。木星是顺行的（黄经递增），
 * 所以 **星纪的黄经必须小于玄枵**。上表满足这一条：星纪 [300,330) 在
 * 玄枵 [270,300) 之后。
 *
 * 这一条约束只能定出「星纪在玄枵之前」，定不出整圈的绝对相位。
 * 绝对相位由第一节的中气锚点给出。两者合起来才唯一。
 *
 * ## 三、还没解决的
 *
 * 这套推法给出的是**木星实际所在**的次，而古代岁星纪年在实际使用中
 * 会因为「超辰」（11.862 年 ≠ 12 年，约 86 年超一次）而采用人为的年份表。
 * 汉代以后改用**太岁纪年**（干支纪年）正是因为超辰麻烦。
 * 所以本模块算的是「岁星实际在哪」，**不是**史书上那一年的纪年——
 * 读史书时需要再叠一层超辰校正，那一层尚未实现。
 */

/**
 * 十二次。**按传统列举顺序**（星纪、玄枵、娵訾、…、析木），
 * 这个顺序同时就是**木星顺行**穿过它们的顺序——见下面「次序」一节。
 *
 * `from` 由 `CI_ORIGIN` 递推，不手写，免得两处不一致。
 */
const CI_NAMES: readonly { readonly name: string; readonly branch: string }[] = [
    { name: "星纪", branch: "丑" },
    { name: "玄枵", branch: "子" },
    { name: "娵訾", branch: "亥" },
    { name: "降娄", branch: "戌" },
    { name: "大梁", branch: "酉" },
    { name: "实沈", branch: "申" },
    { name: "鹑首", branch: "未" },
    { name: "鹑火", branch: "午" },
    { name: "鹑尾", branch: "巳" },
    { name: "寿星", branch: "辰" },
    { name: "大火", branch: "卯" },
    { name: "析木", branch: "寅" }
];

/**
 * 十二次的起始黄经——**整套推法里唯一不确定的常数**。
 *
 * ## 为什么是 270°（冬至）
 *
 * 十二次的绝对相位在文献里有两种安置法，我无法从库里或现有资料判定哪个对，
 * 所以选**能过《左传》那条硬证据**的那一个，并把它写成明面常量：
 *
 * > 《左传·襄公二十八年》「岁在**星纪**而**淫于玄枵**」
 *
 * 「淫于」是"超过"，木星顺行，所以从星纪走进玄枵——
 * **星纪的黄经必须小于玄枵**。`CI_NAMES` 的传统列举顺序正好满足这一条，
 * 于是把星纪的起点放在 270°（冬至），整套就定了。
 *
 * ## 另一种安置法（本文件没有采用）
 *
 * 若要求「每一次包含与它同辰的中气」（玄枵=子=冬至、星纪=丑=大寒、…），
 * 那么玄枵应在 [270,300)、星纪在 [300,330)，**次序与《左传》相反**。
 *
 * 两者不能同时成立。取舍理由：左传那句是**同时代的使用记录**，
 * 而"次含同辰中气"是后世的整理规则；遇到冲突以使用记录为准。
 *
 * ## 怎么改
 *
 * 只改这一个数：`CI_ORIGIN = 300` 就切到另一种安置法。
 * `scripts/verify-twelve-ci.mjs` 会把两种都打印出来供对照。
 */
export const CI_ORIGIN = 270;

/** 十二次的黄经分界与名称。按黄经递增排列（跨 0° 处回绕）。 */
export const TWELVE_CI: readonly { readonly name: string; readonly branch: string; readonly from: number }[] =
    CI_NAMES.map((ci, index) => ({
        name: ci.name,
        branch: ci.branch,
        from: (CI_ORIGIN + index * 30) % 360
    }));

/** 中气名 → 太阳黄经。这是次的分界，也是节气的定义本身。 */
export const MID_TERM_LONGITUDE: Readonly<Record<string, number>> = {
    冬至: 270,
    大寒: 300,
    雨水: 330,
    春分: 0,
    谷雨: 30,
    小满: 60,
    夏至: 90,
    大暑: 120,
    处暑: 150,
    秋分: 180,
    霜降: 210,
    小雪: 240
};

/** 一次的信息。 */
export interface CiPosition {
    /** 次名，如"星纪" */
    name: string;
    /** 对应的十二辰，如"丑" */
    branch: string;
    /** 该次的起始黄经 */
    from: number;
    /** 木星在该次内已走的度数（0–30） */
    progress: number;
    /** 该次的节气跨度文本，如"大寒 → 雨水" */
    span: string;
}

/** 十二次按黄经顺序的节气跨度文案。 */
const SPAN_OF: Readonly<Record<string, string>> = {
    星纪: "冬至 → 大寒",
    玄枵: "大寒 → 雨水",
    娵訾: "雨水 → 春分",
    降娄: "春分 → 谷雨",
    大梁: "谷雨 → 小满",
    实沈: "小满 → 夏至",
    鹑首: "夏至 → 大暑",
    鹑火: "大暑 → 处暑",
    鹑尾: "处暑 → 秋分",
    寿星: "秋分 → 霜降",
    大火: "霜降 → 小雪",
    析木: "小雪 → 冬至"
};
/**
 * 木星黄经 → 它所在的次。
 *
 * ## 实现要点：数组是**环形**的，不是从 0° 排起的
 *
 * `TWELVE_CI` 的第一项是玄枵 [270,300)，往后每项 +30° 并跨过 0°。
 * 所以不能写"取最后一个 from ≤ 黄经 的项"——那个写法对 240° 以上的黄经会
 * 一路退回到 240（娵訾），算出 60° 的"次内进度"。
 * 实测这个 bug 让 270°–359° 全部落错。
 *
 * 正确做法是先平移到以第一项为原点，再按 30° 一档取整：
 *
 * ```
 * shifted = (黄经 − 270 + 360) mod 360
 * index   = floor(shifted / 30)
 * ```
 *
 * @param longitude 木星的地心黄经（度，0–360）
 */
export function ciOfLongitude(longitude: number): CiPosition {
    const normalized = ((longitude % 360) + 360) % 360;

    /* 以第一项（玄枵，270°）为原点平移，于是环形数组变成从 0 起的等距数组 */
    const origin = TWELVE_CI[0]?.from ?? 0;
    const shifted = ((normalized - origin) % 360 + 360) % 360;
    const index = Math.min(TWELVE_CI.length - 1, Math.floor(shifted / 30));
    const hit = TWELVE_CI[index];

    return {
        name: hit.name,
        branch: hit.branch,
        from: hit.from,
        /* 次内进度 = 平移后在该档内的偏移，恒在 [0, 30) */
        progress: shifted - index * 30,
        span: SPAN_OF[hit.name] ?? ""
    };
}

/**
 * 木星黄经 → 「岁在X」这句话。
 *
 * @param longitude 木星的地心黄经（度）
 */
export function ageStarText(longitude: number): string {
    const ci = ciOfLongitude(longitude);
    return `岁在${ci.name}（${ci.branch}次）`;
}
